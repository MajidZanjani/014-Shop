// Actual public Astro/React behavior; consumed only with a freshly qualified static build.
import { readFile, readdir } from 'node:fs/promises';
import { join } from 'node:path';
import { setTimeout as delay } from 'node:timers/promises';
const require = value => { if (!value) throw new Error('public browser assertion'); };
export async function publicSmoke({index,javascript,config,navigate,evaluate,wait,send,cdp,browserContextId,mark,form,responseFault}) {
  let checks=0;
  const key=async (key,code,number) => {
    for (const type of ['keyDown','keyUp']) await send('Input.dispatchKeyEvent',{
      type,key,code,windowsVirtualKeyCode:number,nativeVirtualKeyCode:number});
  };
  const reflow=async label => {
    mark('public-reflow-'+label+'-'+index);
    await send('Emulation.setDeviceMetricsOverride',{width:320,height:900,deviceScaleFactor:1,mobile:false});
    require(await evaluate('innerWidth===320 && document.documentElement.scrollWidth<=innerWidth+1'));checks++;
    await send('Emulation.setDeviceMetricsOverride',{width:javascript?1280:390,height:900,deviceScaleFactor:1,mobile:!javascript});
  };
  const keyboardTarget=async (selector,label) => {
    mark('public-keyboard-'+label+'-'+index);
    await send('Page.bringToFront');
    const focused=`document.activeElement===document.querySelector(${JSON.stringify(selector)})`;
    for(let n=0;n<32 && !await evaluate(focused);n++) await key('Tab','Tab',9);
    require(await evaluate(focused));checks++;
    require(await evaluate(`(() => {const e=document.activeElement,s=getComputedStyle(e),r=e.getBoundingClientRect();
      return e.matches(':focus-visible') && s.outlineStyle!=='none' && parseFloat(s.outlineWidth)>=2
        && r.width>0 && r.height>0 && r.top>=0 && r.bottom<=innerHeight+1;})()`));checks++;
  };
  const namedVendor=async selector => {
    mark('public-accessible-vendor-'+index);
    await send('Accessibility.enable');
    const {root}=await send('DOM.getDocument');
    const {nodeId}=await send('DOM.querySelector',{nodeId:root.nodeId,selector});
    const {node}=await send('DOM.describeNode',{nodeId});
    const {nodes}=await send('Accessibility.getPartialAXTree',{backendNodeId:node.backendNodeId,fetchRelatives:false});
    require(nodes.some(n=>n.backendDOMNodeId===node.backendNodeId && !n.ignored
      && n.role?.value==='combobox' && /vendor/i.test(n.name?.value??'')));checks++;
  };
  mark('public-page-'+index);
  if(javascript) await send('Network.setBlockedURLs',{urls:[config.origin+'/api/v1/customer/session/']});
  await navigate('/');
  require(await evaluate('document.title.includes("Configure your licence") && document.querySelectorAll("h1").length===1 && document.documentElement.lang==="en"'));checks++;
  require(await evaluate('document.body.innerText.includes("Local product preview") && document.querySelector("button").disabled'));checks++;
  if (!javascript) {
    require(await evaluate('getComputedStyle(document.querySelector("astro-island")).display==="none"'));checks++;
    require(await evaluate('document.querySelector("noscript a[href=\\"/purchase/simple/\\"]")!==null'));checks++;
    await reflow('static');
    await keyboardTarget('noscript a','fallback');
    await key('Enter','Enter',13);
    await wait('location.pathname==="/purchase/simple/" && document.readyState==="complete"');
    require(await evaluate('document.querySelector("select[name=vendor]")!==null'));checks++;
    await reflow('django');
    await keyboardTarget('select[name=vendor]','django-vendor');
    await namedVendor('select[name=vendor]');
    await evaluate('document.querySelector("input[name=families][value=altera-agilex-5]").checked=true;true');
    await form('form',{vendor:'altera',term:'rd-annual',fixed_nodes:'1',floating_nodes:'0',support_packages:'0',platform_choice:'not-designed'});
    require(await evaluate('document.body.innerText.includes("Configuration ready for review.") && !document.querySelector("input[name=board_name]")'));checks++;
    require(await evaluate('localStorage.length===0 && sessionStorage.length===0 && !location.search && !location.hash'));checks++;
    return checks;
  }
  await wait('document.querySelector("astro-island") && !document.querySelector("astro-island").hasAttribute("ssr") && document.body.innerText.includes("The shop connection is unavailable")');
  require(await evaluate('document.querySelector("#customer-email").disabled && document.body.innerText.includes("Your selections stay in this page") && !document.body.innerText.includes("--backend")'));checks++;
  require(await evaluate('document.querySelector("#vendor").value===""'));checks++;
  await reflow('react');
  await keyboardTarget('#vendor','react-vendor');
  await namedVendor('#vendor');
  await key('ArrowDown','ArrowDown',40);
  await wait('document.querySelector("#vendor").value==="altera"');checks++;
  mark('public-reconnect-'+index);
  await send('Network.setBlockedURLs',{urls:[]});
  await evaluate('[...document.querySelectorAll("button")].find(e=>e.textContent==="Retry connection").click();true');
  await wait('!document.querySelector("#customer-email").disabled');
  require(await evaluate('document.querySelector("#vendor").value==="altera" && ![...document.querySelectorAll("button")].some(e=>e.textContent==="Retry connection")'));checks++;
  const input=async (selector,value) => {
    await evaluate(`(() => {const e=document.querySelector(${JSON.stringify(selector)});if(!e)throw Error();
      const p=e.tagName==='SELECT'?HTMLSelectElement.prototype:HTMLInputElement.prototype;
      Object.getOwnPropertyDescriptor(p,'value').set.call(e,${JSON.stringify(value)});
      e.dispatchEvent(new Event(e.tagName==='SELECT'?'change':'input',{bubbles:true}));return true;})()`);
  };
  const click=async text => {
    await evaluate(`(() => {const e=[...document.querySelectorAll('button')].find(e=>e.textContent.trim()===${JSON.stringify(text)});if(!e || e.disabled)throw Error();e.click();return true;})()`);
  };
  mark('public-vendor-'+index);
  await input('#vendor','altera');
  mark('public-families-wait-'+index);
  await wait('document.querySelectorAll(".families input").length>0');
  mark('public-terms-'+index);
  require(await evaluate('[...document.querySelectorAll("input[name=term]")].some(e=>e.value==="rdp-yearly")'));checks++;
  mark('public-family-select-'+index);
  await evaluate('document.querySelector(".families input").click();true');
  await wait('document.querySelector(".families input").checked');
  mark('public-term-select-'+index);
  await evaluate('document.querySelector("input[name=term][value=\\"rd-annual\\"]").click();true');
  mark('public-access-mode-'+index);
  await evaluate('[...document.querySelectorAll("label.choice")].find(e=>e.textContent.includes("Fixed / node-locked")).querySelector("input").click();true');
  mark('public-required-platform-'+index);
  require(await evaluate('document.querySelector(".validation").innerText.includes("Complete your configuration")'));checks++;
  mark('public-platform-'+index);
  await input('#platform','not-designed');
  await wait('document.querySelector(".validation").innerText.includes("Configuration ready for review")');
  require(await evaluate('!document.querySelector("#board-name") && document.querySelector(".summary").innerText.includes("Board not designed or selected")'));checks++;
  mark('public-other-board-'+index);
  await input('#platform','other-board');
  await wait('document.querySelector("#board-name")!==null');
  await input('#board-name','Synthetic public board');
  await wait('document.querySelector(".summary").innerText.includes("Synthetic public board")');checks++;
  mark('public-ready-kit-'+index);
  await input('#platform','listed-kit');
  await wait('document.querySelector(".validation").innerText.includes("Choose an applicable platform")');
  require(await evaluate('!document.querySelector("#board-name") && document.body.innerText.includes("No approved ready-kit entries")'));checks++;
  await input('#platform','not-designed');
  mark('public-vendor-reset-'+index);
  await input('#vendor','amd-xilinx');
  await wait('document.querySelectorAll(".families input").length>0 && document.querySelectorAll("input[name=term]").length===2');
  require(await evaluate('![...document.querySelectorAll("input[name=term]")].some(e=>e.value==="rdp-yearly") && ![...document.querySelectorAll(".families input")].some(e=>e.checked) && ![...document.querySelectorAll("input[name=term]")].some(e=>e.checked)'));checks++;
  mark('public-config-return-'+index);
  // Return to a valid Altera configuration, proving vendor changes reset incompatible choices.
  await input('#vendor','altera');
  await wait('document.querySelectorAll("input[name=term]").length===3');
  await evaluate('document.querySelector(".families input").click();document.querySelector("input[name=term][value=\\"rd-annual\\"]").click();[...document.querySelectorAll("label.choice")].find(e=>e.textContent.includes("Fixed / node-locked")).querySelector("input").click();true');
  mark('public-support-count-'+index);
  await input('#support','2');
  await wait('document.querySelector(".summary").innerText.includes("20 hours") && document.querySelector(".validation").innerText.includes("Configuration ready for review")');checks++;
  mark('public-layout-'+index);
  require(await evaluate('document.documentElement.scrollWidth<=innerWidth+1'));checks++;
  require(await evaluate(`[...document.querySelectorAll('input:not([type=hidden]),select,button')].every(e=>e.disabled||e.labels?.length||e.getAttribute('aria-label')||(e.tagName==='BUTTON'&&e.textContent.trim()))`));checks++;
  mark('public-access-'+index);
  const before=new Set(await readdir(config.mailbox));
  await input('#customer-email','browser-public-'+index+'@synthetic.invalid');
  await click('Request verification code');
  await wait('document.querySelector("#customer-code")!==null');
  let added=[];
  for(let n=0;n<50;n++) {added=(await readdir(config.mailbox)).filter(n=>!before.has(n));if(added.length)break;await delay(50);}
  require(added.length===1);
  const mail=await readFile(join(config.mailbox,added[0]),'utf8');require(mail.length<16384);
  const code=mail.match(/^Verification code: ([A-Za-z0-9_-]+)$/m)?.[1];require(code);
  await input('#customer-code',code);await click('Verify and continue');
  await wait('document.body.innerText.includes("Verified customer session") && !document.querySelector("section[aria-label=\\"Draft cart\\"] fieldset").disabled');checks++;
  mark('public-offline-save-'+index);
  await send('Network.emulateNetworkConditions',{offline:true,latency:0,downloadThroughput:-1,uploadThroughput:-1});
  await click('Save configuration draft');
  await wait('document.body.innerText.includes("The backend could not confirm this action")');
  require(await evaluate('document.querySelector("#platform").value==="not-designed" && document.querySelector("#support").value==="2" && ![...document.querySelectorAll("button")].some(e=>e.textContent.startsWith("Resume draft")) && localStorage.length===0 && sessionStorage.length===0'));checks++;
  await send('Network.emulateNetworkConditions',{offline:false,latency:0,downloadThroughput:-1,uploadThroughput:-1});
  mark('public-save-'+index);
  await click('Save configuration draft');
  await wait('document.body.innerText.includes("Configuration saved as a local draft") && [...document.querySelectorAll("button")].some(e=>e.textContent.startsWith("Resume draft"))');checks++;
  require(await evaluate('[...document.querySelectorAll("button")].filter(e=>e.textContent.startsWith("Resume draft")).length===1'));checks++;
  const armLoss=path=>{responseFault.url=config.origin+path;responseFault.armed=true;responseFault.posts=[];responseFault.dropped=0;};
  const exactReplay=()=>{
    require(responseFault.dropped===1 && responseFault.posts.length===2 && responseFault.posts[0]===responseFault.posts[1]);checks++;
    responseFault.url=null;responseFault.posts=[];
  };
  mark('public-cart-'+index);
  armLoss('/api/v1/cart/');
  await click('Add current configuration to cart');
  await wait('document.body.innerText.includes("Save outcome uncertain")');
  require(await evaluate(`document.querySelector('section[aria-label="Draft cart"] fieldset').disabled && [...document.querySelectorAll('button')].filter(e=>['Reload cart','Request quotation for saved cart'].includes(e.textContent.trim())).every(e=>e.disabled)`));checks++;
  await click('Retry last cart save');
  await wait('document.querySelector("section[aria-label=\\"Draft cart\\"]").innerText.includes("Version 1")');
  require(await evaluate('document.querySelectorAll("section[aria-label=\\"Draft cart\\"] fieldset ol>li").length===2 && document.querySelector("section[aria-label=\\"Draft cart\\"]").innerText.includes("2 packages")'));checks++;
  exactReplay();
  mark('public-quote-'+index);
  armLoss('/api/v1/quotation-requests/');
  await click('Request quotation for saved cart');
  await wait('document.body.innerText.includes("Quotation request outcome uncertain")');
  require(await evaluate(`document.querySelector('section[aria-label="Draft cart"] fieldset').disabled && [...document.querySelectorAll('button')].filter(e=>['Reload cart','Reload request history'].includes(e.textContent.trim())).every(e=>e.disabled)`));checks++;
  await click('Retry quotation request');
  await wait('document.querySelector("section[aria-label=\\"Captured quotation request\\"]")!==null');
  require(await evaluate('document.querySelector("section[aria-label=\\"Captured quotation request\\"]").innerText.includes("Acceptance and payment disabled")'));checks++;
  exactReplay();
  await wait(`document.querySelectorAll('section[aria-label="Draft cart"] > ol > li').length===1`);
  require(await evaluate(`document.querySelectorAll('section[aria-label="Draft cart"] > ol > li').length===1`));checks++;
  mark('public-competing-cart-'+index);
  require(await evaluate(`(async()=>{
    const options={credentials:'same-origin',cache:'no-store',redirect:'error'};
    const session=await fetch('/api/v1/customer/session/',options).then(r=>r.json());
    const cart=await fetch('/api/v1/cart/',options).then(r=>r.json());
    const lines=cart.lines.map(line=>line.kind==='support'?{...line,quantity:3}:line);
    const response=await fetch('/api/v1/cart/',{...options,method:'POST',headers:{'Content-Type':'application/json','X-CSRFToken':session.csrf_token},body:JSON.stringify({request_id:crypto.randomUUID(),expected_version:cart.current_version,catalog_revision:cart.catalog_revision,lines})});
    const saved=await response.json();
    return response.status===201 && saved.current_version===2 && saved.lines.length===2 && document.querySelector('section[aria-label="Draft cart"]').innerText.includes('Version 1');
  })()`));checks++;
  await click('Add support packages only');
  await wait('document.body.innerText.includes("Cart changed in another tab or catalog revision")');
  require(await evaluate(`document.querySelector('section[aria-label="Draft cart"] fieldset').disabled && ![...document.querySelectorAll('button')].some(e=>e.textContent==='Retry last cart save')`));checks++;
  await click('Reload cart');
  await wait(`document.querySelector('section[aria-label="Draft cart"]').innerText.includes('Version 2') && !document.querySelector('section[aria-label="Draft cart"] fieldset').disabled`);
  require(await evaluate(`document.querySelectorAll('section[aria-label="Draft cart"] fieldset ol>li').length===2 && document.querySelector('section[aria-label="Draft cart"] fieldset').innerText.includes('3 packages')`));checks++;
  require(await evaluate(`(async()=>{const r=await fetch('/api/v1/cart/',{credentials:'same-origin',cache:'no-store',redirect:'error'});const c=await r.json();return r.status===200 && c.current_version===2 && c.lines.length===2 && c.lines.find(line=>line.kind==='support').quantity===3;})()`));checks++;
  const refreshPath=await evaluate(`document.querySelector('section[aria-label="Captured quotation request"] a').pathname.replace('/purchase/quotation-business/','/api/v1/quotation-requests/')`);
  let refreshed=false;
  const refreshListener=event=>{if(event.method==='Network.responseReceived' && event.params.response.url===config.origin+refreshPath && event.params.response.status===200)refreshed=true;};
  cdp.events.push(refreshListener);
  await click('Refresh captured request status');
  for(let n=0;n<100 && !refreshed;n++)await delay(50);
  cdp.events.splice(cdp.events.indexOf(refreshListener),1);
  await wait(`![...document.querySelectorAll('button')].find(e=>e.textContent==='Refresh captured request status').disabled`);
  require(refreshed && await evaluate(`document.querySelector('section[aria-label="Captured quotation request"]').innerText.includes('Saved version 1') && document.querySelector('section[aria-label="Captured quotation request"]').innerText.includes('Support: 2 ten-hour packages') && !document.querySelector('section[aria-label="Captured quotation request"]').innerText.includes('Support: 3 ten-hour packages')`));checks++;
  await input('#platform','other-board');await wait('document.querySelector("#board-name")!==null');
  await evaluate('[...document.querySelectorAll("button")].find(e=>e.textContent.startsWith("Resume draft")).click();true');
  await wait('document.querySelector("#platform").value==="not-designed" && !document.querySelector("#board-name")');checks++;
  require(await evaluate('localStorage.length===0 && sessionStorage.length===0 && !location.search && !location.hash'));checks++;
  const cookies=await cdp.send('Storage.getCookies',{browserContextId});
  require(cookies.cookies.some(e=>e.name===config.session_cookie&&e.httpOnly));checks++;
  mark('public-expired-session-'+index);
  require(await evaluate(`(async()=>{const options={credentials:'same-origin',cache:'no-store',redirect:'error'};const s=await fetch('/api/v1/customer/session/',options).then(r=>r.json());const r=await fetch('/api/v1/customer/logout/',{...options,method:'POST',headers:{'Content-Type':'application/json','X-CSRFToken':s.csrf_token},body:'{}'});return r.status===200 && (await r.json()).authenticated===false;})()`));checks++;
  await click('Reload cart');
  await wait('document.body.innerText.includes("Your session expired.")');
  require(await evaluate(`!document.querySelector('section[aria-label="Draft cart"]') && !document.querySelector('section[aria-label="Captured quotation request"]') && document.querySelector('#vendor').value==='' && document.querySelector('#customer-email').value==='' && !document.querySelector('#customer-code') && ![...document.querySelectorAll('button')].some(e=>e.textContent.startsWith('Resume draft'))`));checks++;
  mark('public-expired-reverify-'+index);
  await wait('document.querySelector("#customer-email") && !document.querySelector("#customer-email").disabled');
  const priorMail=new Set(await readdir(config.mailbox));
  await input('#customer-email','browser-public-'+index+'@synthetic.invalid');
  await click('Request verification code');
  await wait('document.querySelector("#customer-code")!==null');
  let renewed=[];
  for(let n=0;n<50;n++){renewed=(await readdir(config.mailbox)).filter(n=>!priorMail.has(n));if(renewed.length)break;await delay(50);}
  require(renewed.length===1);
  const renewedMail=await readFile(join(config.mailbox,renewed[0]),'utf8');require(renewedMail.length<16384);
  const renewedCode=renewedMail.match(/^Verification code: ([A-Za-z0-9_-]+)$/m)?.[1];require(renewedCode);
  await input('#customer-code',renewedCode);await click('Verify and continue');
  await wait(`document.querySelector('section[aria-label="Draft cart"]')?.innerText.includes('Version 2') && [...document.querySelectorAll('button')].some(e=>e.textContent.startsWith('Resume draft'))`);checks++;
  await wait(`document.querySelectorAll('section[aria-label="Draft cart"] > ol > li').length===1`);
  await click('Review captured request');
  await wait(`document.querySelector('section[aria-label="Captured quotation request"]')?.innerText.includes('Saved version 1')`);
  require(await evaluate(`document.querySelector('section[aria-label="Captured quotation request"]').innerText.includes('Support: 2 ten-hour packages') && document.querySelector('section[aria-label="Draft cart"] fieldset').innerText.includes('3 packages') && localStorage.length===0 && sessionStorage.length===0`));checks++;
  mark('public-logout-'+index);
  await click('Sign out');
  await wait('document.body.innerText.includes("Signed out.") && document.querySelector("#vendor").value===""');
  require(await evaluate('!document.querySelector("section[aria-label=\\"Draft cart\\"]") && !document.querySelector("#customer-code")'));checks++;
  mark('public-logout-denial-'+index);
  require(await evaluate(`(async()=>{
    const paths=['/api/v1/configuration-drafts/','/api/v1/cart/',${JSON.stringify(refreshPath)}];
    const replies=await Promise.all(paths.map(path=>fetch(path,{credentials:'same-origin',cache:'no-store',redirect:'error'})));
    return replies.every(r=>r.status===401 && r.headers.get('cache-control')?.includes('no-store'));
  })()`));checks++;
  require(await evaluate(`(async()=>{const r=await fetch('/api/v1/customer/session/',{credentials:'same-origin',cache:'no-store',redirect:'error'});const s=await r.json();return r.status===200 && s.authenticated===false;})()`));checks++;
  await navigate('/');
  await wait('document.querySelector("#customer-email") && !document.querySelector("#customer-email").disabled');
  require(await evaluate(`!document.querySelector('section[aria-label="Draft cart"]') && !document.querySelector('section[aria-label="Captured quotation request"]') && !document.querySelector('#customer-code') && ![...document.querySelectorAll('button')].some(e=>e.textContent.startsWith('Resume draft')) && document.querySelector('#vendor').value===''`));checks++;
  require(await evaluate('localStorage.length===0 && sessionStorage.length===0 && !location.search && !location.hash'));checks++;
  return checks;
}
