#!/usr/bin/env python3
"""Compile the public draft catalog. No approvals, private data or live offers."""
import argparse
import hashlib
import json
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'frontend/src/content/products/xspi.md'

def unique_object(pairs):
    value={}
    for key,item in pairs:
        if key in value: raise ValueError('duplicate catalog key')
        value[key]=item
    return value

def compile_catalog(check=False):
    text = SOURCE.read_text()
    data = json.loads(text.split('---', 2)[1],object_pairs_hook=unique_object) # JSON is a strict YAML subset.
    expected = {'schema_version','product_id','support_product_id','profile_id','title','site','source_sha256','vendors','terms','production_bands','approvals','money','support_seconds_per_package','purchase_flow'}
    assert set(data) == expected, 'unknown/missing catalog field'
    assert type(data['schema_version']) is int and data['schema_version'] == 1 and data['product_id'] == 'sll-xspi-mc'
    assert data['support_product_id'] == 'sll-xspi-mc-support-10h' and data['profile_id'] == 'sll-xspi-mc-v1'
    assert data['site'] == 'https://shop.xspi.pro' and data['support_seconds_per_package'] == 36000
    authority = (ROOT / 'docs/product-source/SLL_xSPI_MC_Product_Page.md').read_bytes()
    assert data['source_sha256'] == hashlib.sha256(authority).hexdigest(), 'authority digest mismatch'
    expected_families = [
      ('altera','Altera / Intel FPGA',['Cyclone 10 LP (C10LP)','MAX 10','Cyclone 10','Cyclone 10 GX','Cyclone V','Stratix 10','Agilex 3','Agilex 5']),
      ('amd-xilinx','AMD / Xilinx',['Series 7','UltraScale','UltraScale+']),
      ('microchip','Microchip',['PolarFire','PolarFire SoC'])]
    assert len(data['vendors']) == 3
    ids = []
    for vendor, (identity, label, families) in zip(data['vendors'], expected_families):
        assert set(vendor) == {'id','label','families'} and vendor['id'] == identity and vendor['label'] == label
        assert [f['label'] for f in vendor['families']] == families
        for family in vendor['families']:
            assert set(family) == {'id','label'} and family['label'].encode() in authority
            assert family['id'] and family['id'] not in ids
            proposal = (ROOT / 'SLL-xSPI-MC-Shop-Proposal-2026-10-21.md').read_text()
            assert ('| '+family['label']+' | `'+family['id']+'` |') in proposal, 'family ID not in authority table'
            ids.append(family['id'])
    assert [(t['id'],t['vendors']) for t in data['terms']] == [('rd-annual',['altera','amd-xilinx','microchip']),('rdp-yearly',['altera']),('perpetual',['altera','amd-xilinx','microchip'])]
    assert [t['label'] for t in data['terms']] == ['R&D — annual','RDP — yearly','Perpetual']
    for t in data['terms']: assert set(t) == {'id','label','vendors','description'} and isinstance(t['description'],str)
    assert [(b['id'],b['minimum'],b['maximum']) for b in data['production_bands']] == [('units-1-100',1,100),('units-101-1000',101,1000),('units-1001-5000',1001,5000),('higher-volume',5001,None)]
    for b in data['production_bands']: assert set(b) == {'id','label','minimum','maximum'}
    assert set(data['approvals']) == {'prices','rights','access','coverage','terms','recurrence','production_accounting'}
    assert all(v is None for v in data['approvals'].values()), 'approval requires protected workflow, never catalog editing'
    assert set(data['money']) == {'currency','currency_status','base_minor','additional_family_minor','production_minor','mode_minor','node_minor','support_minor','tax_minor','total_minor'}
    assert data['money']['currency'] == 'EUR' and data['money']['currency_status'] == 'draft'
    assert all(v is None for k,v in data['money'].items() if k.endswith('_minor')), 'unapproved draft rates forbidden'
    flow=data['purchase_flow']
    assert set(flow)=={'amendment_sha256','platform_choices','ready_kits','offer_policy_revision'}
    assert flow['amendment_sha256']==hashlib.sha256((ROOT/'014-Shop-Board-Support-Amendment-2026-10-26.md').read_bytes()).hexdigest()
    assert flow['platform_choices']==['listed-kit','other-board','not-designed']
    assert flow['ready_kits']==[] and flow['offer_policy_revision'] is None, 'actual kit/offer approvals not supplied'
    raw = json.dumps(data,ensure_ascii=False,sort_keys=True,separators=(',',':')).encode()
    revision = hashlib.sha256(raw).hexdigest()
    manifest = dict(revision=revision, **data)
    outputs = {
      ROOT / 'catalog/revisions' / (revision+'.json'): json.dumps(manifest,ensure_ascii=False,indent=2)+'\n',
      ROOT / 'backend/shop/catalog/revision.json': json.dumps(manifest,ensure_ascii=False,indent=2)+'\n',
      ROOT / 'frontend/src/lib/catalog.ts': '// Generated by scripts/compile_catalog.py; do not edit.\nexport const catalog = '+json.dumps(manifest,ensure_ascii=False,indent=2)+' as const;\n',
    }
    for path,content in outputs.items():
        if check: assert path.is_file() and path.read_text() == content, 'stale catalog output: '+str(path.relative_to(ROOT))
        else:
            path.parent.mkdir(parents=True,exist_ok=True)
            if path.parent.name == 'revisions' and path.exists(): assert path.read_text() == content, 'immutable revision collision'
            else: path.write_text(content)
    print('CATALOG_PASS revision='+revision+' checks=1')
    return manifest

if __name__ == '__main__':
    p=argparse.ArgumentParser();p.add_argument('--check',action='store_true');a=p.parse_args();compile_catalog(a.check)
